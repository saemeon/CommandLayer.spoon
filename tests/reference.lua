local function commandIds(K)
  local ids = {}
  for _, command in ipairs(K.getCommands()) do ids[#ids + 1] = command.id end
  table.sort(ids)
  return ids
end

function R.keybindingsSchema(K)
  local fields = K.keybindingFields
  return {
    ["$schema"] = DRAFT, ["$comment"] = COMMENT,
    title = "Command Layer keybindings",
    description = "keybindings.json: entries after the Spoon's config/defaultKeybindings.jsonc.",
    type = "array",
    items = {
      type = "object",
      properties = {
        key = { type = "string", description = fields.key },
        command = { description = fields.command,
                    anyOf = { { type = "string", enum = commandIds(K) }, { type = "string", pattern = "^-" } } },
        args = { description = fields.args },
        when = { type = "string", description = fields.when },
        global = { type = "boolean", description = fields.global },
        ["repeat"] = { type = "boolean", description = fields["repeat"] },
      },
      required = { "command" },
      additionalProperties = false,
    },
  }
end

