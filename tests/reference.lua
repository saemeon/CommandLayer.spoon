local function cell(text)
  return (tostring(text or ""):gsub("\n", " "):gsub("|", "\\|"))
end

local function code(text) return "`" .. cell(text) .. "`" end

local function typeName(field)
  local words = {}
  for _, luaType in ipairs(luaTypes(field)) do
    if luaType == "table" and field.list then words[#words + 1] = "list of " .. field.list .. "s"
    elseif luaType == "table" and field.map then words[#words + 1] = "table of " .. field.map .. "s by key"
    elseif luaType == "table" and field.items then words[#words + 1] = "list of " .. field.items .. "s"
    elseif luaType == "when" then words[#words + 1] = "when clause"
    else words[#words + 1] = luaType end
  end
  return table.concat(words, " or ")
end

local function withEnum(description, enum)
  if type(enum) ~= "table" then return description end
  local values = {}
  for i, value in ipairs(enum) do values[i] = code(value) end
  return (description or "") .. " One of " .. table.concat(values, ", ") .. "."
end

local function jsonCell(K, value)
  if value == nil then return "" end
  return code(K.encodeJSON(value, true))
end

function R.reference(K)
  local out = {}
  local function line(text) out[#out + 1] = text or "" end
  local function table_(header)
    line("| " .. table.concat(header, " | ") .. " |")
    line("|" .. ("---|"):rep(#header))
  end
  local function row(cells) line("| " .. table.concat(cells, " | ") .. " |") end

  line("# Command Layer reference")
  line()
  line("Generated by `lua tests/reference.lua` from `core/schema.lua`, `core/api.lua` and the plugins")
  line("that ship. Do not edit it: change those and generate it again. The harness fails while it is out of date.")
  line()
  line("## Specs")
  for _, kind in ipairs(sortedKeys(K.schemas)) do
    local schema = K.schemas[kind]
    line()
    line("### " .. kind)
    line()
    line(schema.description)
    line()
    table_({ "Field", "Type", "Required", "Description" })
    for _, name in ipairs(sortedKeys(schema.fields)) do
      local field = schema.fields[name]
      row({ code(name), cell(typeName(field)), field.required and "yes" or "",
            cell(withEnum(field.description, field.enum)) })
    end
  end

  local defaults = shippedDefaults(K)
  line()
  line("## Lists")
  line()
  line("What an extension reads of the layer's own lists. Each call gives a fresh copy, every entry holding")
  line("these fields and no other; changing one changes nothing the layer holds.")
  for _, name in ipairs(sortedKeys(K.listShapes)) do
    local shape = K.listShapes[name]
    line()
    line("### " .. name)
    line()
    line(shape.description)
    line()
    table_({ "Field", "Type", "Description" })
    for _, field in ipairs(sortedKeys(shape.fields)) do
      row({ code(field), cell(typeName(shape.fields[field])), cell(shape.fields[field].description) })
    end
  end

  line()
  line("## Settings")
  line()
  line("A profile's `settings.json` sets any of these over `config/defaults.jsonc`. An editor completes and")
  line("checks it when it starts with `\"$schema\"` naming the Spoon's `config/settings.schema.json`; VS Code's")
  line("`json.schemas` setting does the same for `keybindings.json` with `config/keybindings.schema.json`.")
  line()
  line("### The kernel's")
  line()
  table_({ "Key", "Type", "Default", "Description" })
  for _, key in ipairs(sortedKeys(K.kernelSettings)) do
    local doc = K.kernelSettings[key]
    row({ code(key), doc.type, key == "views" and "" or jsonCell(K, defaults[key]), cell(doc.description) })
    for _, sub in ipairs(sortedKeys(doc.properties or {})) do
      local subdoc = doc.properties[sub]
      row({ code(key .. "." .. sub), subdoc.type, jsonCell(K, type(defaults[key]) == "table" and defaults[key][sub] or nil),
            cell(subdoc.description) })
    end
  end

  line()
  line("### Declared by extensions, presenters and rankers")
  for _, owner in ipairs(settingOwners(K)) do
    line()
    line(("#### %s (`%s`, %s)"):format(owner.displayName, owner.name, owner.kind))
    if owner.description then
      line()
      line(owner.description)
    end
    line()
    table_({ "Setting", "Type", "Default", "Description" })
    if owner.kind == "extension" then
      row({ code(owner.name .. ".enabled"), "boolean",
            code(tostring(defaults[owner.name .. ".enabled"] ~= false)), cell(enabledDescription(owner)) })
      row({ code(owner.name .. ".menus"), "object", "", cell(MENUS_DESCRIPTION) })
    end
    local settings = type(owner.settings) == "table" and owner.settings or {}
    local keys = sortedKeys(settings)
    table.sort(keys, function(a, b) return K.settingBefore(settings, a, b) end)
    for _, key in ipairs(keys) do
      local decl = settings[key]
      if type(decl) == "table" then
        local about = decl.markdownDescription or decl.description
        if decl.deprecationMessage then about = (about or "") .. " Deprecated: " .. decl.deprecationMessage end
        row({ code(owner.name .. "." .. key), cell(decl.type), jsonCell(K, decl.default),
              cell(withEnum(about, decl.enum)) })
      end
    end
  end

  line()
  line("## Keybindings")
  line()
  line("`keybindings.json` is a list of entries, each after the shipped `config/defaultKeybindings.jsonc`.")
  line()
  table_({ "Field", "Required", "Description" })
  for _, name in ipairs(sortedKeys(K.keybindingFields)) do
    row({ code(name), name == "command" and "yes" or "", cell(K.keybindingFields[name]) })
  end

  line()
  line("## Plugin API")
  line()
  line("What `cl` holds for each kind of plugin. Reading or writing any other name raises.")
  local members = K.apiMembers()
  for _, kind in ipairs(sortedKeys(members)) do
    line()
    line("### " .. kind)
    line()
    table_({ "Member", "Description" })
    for _, member in ipairs(members[kind]) do row({ code(member.name), cell(member.description) }) end
  end

  line()
  line("## Commands")
  line()
  line("Every command the shipped extensions and the kernel register, by id.")
  line()
  table_({ "Command", "Title", "Extension" })
  local commands = K.getCommands()
  table.sort(commands, function(a, b) return a.id < b.id end)
  for _, command in ipairs(commands) do
    local title = command.category and (command.category .. ": " .. command.title) or command.title
    row({ code(command.id), cell(title), command.extension and code(command.extension) or "kernel" })
  end

  return table.concat(out, "\n") .. "\n"
end

----------------------------------------------------------------------

function R.generate(K)
  return {
    ["config/settings.schema.json"] = K.encodeJSON(R.settingsSchema(K)) .. "\n",
    ["config/keybindings.schema.json"] = K.encodeJSON(R.keybindingsSchema(K)) .. "\n",
    ["docs/api.md"] = R.reference(K),
  }
end

if given == T then return R end

local K = R.kernel()
local files = R.generate(K)
os.execute(("mkdir -p %q"):format(T.dir .. "docs"))
for _, path in ipairs(R.FILES) do
  local handle = assert(io.open(T.dir .. path, "w"))
  handle:write(files[path])
  handle:close()
  print("wrote " .. path)
end
