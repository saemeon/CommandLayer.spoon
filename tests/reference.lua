-- CommandLayer.spoon/tests/reference.lua
-- Writes docs/api.md, config/settings.schema.json and
-- config/keybindings.schema.json from the schema, the plugin API and the
-- plugins that ship. Run with:  lua tests/reference.lua   (from the Spoon's
-- folder). Not a suite: tests/generated.lua loads it to check the files on
-- disk are what it would write.

local given = ...
local T = type(given) == "table" and given or nil
if not T then
  local dir = arg and arg[0] and arg[0]:match("^(.-)tests/[^/]*$") or ""
  T = assert(loadfile((dir == "" and "./" or dir) .. "tests/harness.lua"))(dir == "" and "./" or dir)
end

local R = {}

R.FILES = { "config/keybindings.schema.json", "config/settings.schema.json", "docs/api.md" }

local DRAFT = "http://json-schema.org/draft-07/schema#"
local COMMENT = "Generated by `lua tests/reference.lua`; do not edit."

-- The shipped files alone: a person's own folder would change what is written.
-- Every extension on, so a command of one shipped switched off is still one a
-- keybinding may name.
function R.kernel()
  return T.setup(T.loadKernel(), T.everyExtensionOn)
end

----------------------------------------------------------------------
-- HELPERS
----------------------------------------------------------------------

local function sortedKeys(t)
  local keys = {}
  for key in pairs(t) do keys[#keys + 1] = key end
  table.sort(keys, function(a, b) return tostring(a) < tostring(b) end)
  return keys
end

-- encodeJSON writes an empty list as {}, so an empty table is left out.
local function isEmpty(value)
  return type(value) == "table" and next(value) == nil
end

local function luaTypes(field)
  return type(field.type) == "table" and field.type or { field.type }
end

local function presenterNames(K) return sortedKeys(K.presenters) end

local function matcherNames(K)
  local names = {}
  for _, matcher in ipairs(K.loadedMatchers or K.matchers) do names[#names + 1] = matcher.name end
  table.sort(names)
  return names
end

local JSON_OF_LUA = { string = "string", when = "string", number = "number", boolean = "boolean" }

----------------------------------------------------------------------
-- settings.schema.json
----------------------------------------------------------------------

local kindSchema

-- A spec field as a settings file writes it; nil for one only code can hold.
local function fieldSchema(K, field)
  local out, types = { description = field.description }, {}
  for _, luaType in ipairs(luaTypes(field)) do
    if JSON_OF_LUA[luaType] then
      types[#types + 1] = JSON_OF_LUA[luaType]
    elseif luaType == "table" and field.list then
      types[#types + 1], out.items = "array", kindSchema(K, field.list)
    elseif luaType == "table" and field.items then
      types[#types + 1], out.items = "array", { type = JSON_OF_LUA[field.items] }
    elseif luaType == "table" and field.map then
      types[#types + 1], out.additionalProperties = "object", kindSchema(K, field.map)
    elseif luaType == "table" then
      types[#types + 1] = "array"
      types[#types + 1] = "object"
    end
  end
  -- Only a function: nothing a file can hold.
  if #types == 0 and luaTypes(field)[1] ~= "any" then return nil end
  if #types == 1 then out.type = types[1] elseif #types > 1 then out.type = types end
  if field.enum then out.enum = field.enum end
  if field.presenter then out.enum = presenterNames(K) end
  return out
end

function kindSchema(K, kind, extra)
  local schema = K.schemas[kind]
  local properties, required = {}, {}
  for name, field in pairs(schema.fields) do
    if field.inFiles ~= false then
      properties[name] = fieldSchema(K, field)
      if field.required and properties[name] then required[#required + 1] = name end
    end
  end
  for name, field in pairs(extra or {}) do properties[name] = fieldSchema(K, field) end
  table.sort(required)
  local out = { type = "object", description = schema.description, properties = properties,
                additionalProperties = false }
  if #required > 0 then out.required = required end
  return out
end

local DECLARATION_KEYS = { "type", "default", "description", "markdownDescription", "enum", "enumDescriptions",
                           "minimum", "maximum", "deprecationMessage", "order" }

-- VS Code's own keys for a setting, pattern left out: ours is a Lua pattern,
-- which a JSON Schema would read as a regular expression.
local function declarationSchema(decl)
  local out = {}
  for _, key in ipairs(DECLARATION_KEYS) do
    if decl[key] ~= nil and not isEmpty(decl[key]) then out[key] = decl[key] end
  end
  return out
end

local function settingOwners(K)
  local owners = K.settingOwners()
  table.sort(owners, function(a, b)
    if a.displayName:lower() ~= b.displayName:lower() then return a.displayName:lower() < b.displayName:lower() end
    return a.name < b.name
  end)
  return owners
end

local function shippedDefaults(K)
  return K.decodeJSONC(K.readText(K.SPOON_DIR .. "config/defaults.jsonc")) or {}
end

local MENUS_DESCRIPTION = "Which pickers its rows and commands are in, over what it declares: a menu's "
  .. "name to true (added) or false (taken out); a menu not named keeps the declaration. "
  .. "A command that is no row anywhere stays none."

local function enabledDescription(owner)
  return ("Whether %s is on; a change applies on reload.%s"):format(owner.displayName,
    owner.description and (" " .. owner.description .. ".") or "")
end

function R.settingsSchema(K)
  local defaults, properties = shippedDefaults(K), {}
  properties["$schema"] = { type = "string",
                            description = "Where an editor finds this file: the Spoon's config/settings.schema.json." }

  for key, doc in pairs(K.kernelSettings) do
    local p = { type = doc.type, description = doc.description }
    local default = defaults[key]
    if default ~= nil and not isEmpty(default) and key ~= "views" then p.default = default end
    for sub, subdoc in pairs(doc.properties or {}) do
      p.properties = p.properties or {}
      local sp = { type = subdoc.type, description = subdoc.description }
      local subDefault = type(default) == "table" and default[sub] or nil
      if subDefault ~= nil and not isEmpty(subDefault) then sp.default = subDefault end
      if subdoc.type == "object" then sp.additionalProperties = { type = "string" } end
      p.properties[sub] = sp
    end
    if doc.properties then p.additionalProperties = false end
    properties[key] = p
  end

  properties.views.items = kindSchema(K, "view", K.kernelSettings.views.fields)
  properties.matchers.items = { type = "string", enum = matcherNames(K) }
  properties.rankers.properties, properties.rankers.additionalProperties = {}, false
  for _, ranker in ipairs(K.rankers) do
    properties.rankers.properties[ranker.name] = { type = "number", description = ranker.description }
  end
  properties.prefixes.additionalProperties = { type = { "string", "array" }, items = { type = "string" } }
  properties.aliases.additionalProperties = { type = { "string", "array" }, items = { type = "string" } }
  properties.presenter.enum = presenterNames(K)
  properties.logLevel.enum = K.logLevels

  local names = {}
  for _, owner in ipairs(settingOwners(K)) do
    names[#names + 1] = owner.name
    if owner.kind == "extension" then
      properties[owner.name .. ".enabled"] = { type = "boolean", default = defaults[owner.name .. ".enabled"] ~= false,
                                               description = enabledDescription(owner) }
      properties[owner.name .. ".menus"] = { type = "object", additionalProperties = { type = "boolean" },
                                             description = MENUS_DESCRIPTION }
    end
    for key, decl in pairs(type(owner.settings) == "table" and owner.settings or {}) do
      if type(decl) == "table" then properties[owner.name .. "." .. key] = declarationSchema(decl) end
    end
  end
  table.sort(names)

  return {
    ["$schema"] = DRAFT, ["$comment"] = COMMENT,
    title = "Command Layer settings",
    description = "settings.json, over the Spoon's config/defaults.jsonc.",
    type = "object",
    properties = properties,
    -- A dotted key naming nothing that ships is a person's own extension's.
    patternProperties = {
      ["^(?!(?:" .. table.concat(names, "|") .. ")\\.)[A-Za-z0-9_-]+\\."] = {
        description = "A setting of an extension, presenter or ranker that does not ship with the Spoon.",
      },
    },
    additionalProperties = false,
  }
end

